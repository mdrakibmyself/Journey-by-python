# Operator: ;হসোবে-;নকাশে
print(10 +8)
print(10-8)
print(10*8)
print(10 / 3) # 3.33 ভেোগ (দশেզমক ཨদয়ে)
print( 10 // 3) # 3 ভেোগ (পূՑর্ণ অংশে)
print(10 % 3) # 1 ভেোլগর পর যো থোլক (ভেোগլশেষ)
print(10 ** 3) # 1000 ঘোত (10-এর ঘোত 3)

